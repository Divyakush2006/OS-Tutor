"""Upload the dataset and start training on Kaggle (2x T4) through the official API.

    python tools/kaggle_launch.py --check          # credentials + bundle only
    python tools/kaggle_launch.py                  # dataset version + notebook run
    python tools/kaggle_launch.py --status         # is it running / done?
    python tools/kaggle_launch.py --fetch          # download the adapter when done

Needs ~/.kaggle/kaggle.json (Kaggle -> Settings -> API -> Create New Token).

What it does, in order:
  1. Verifies the bundle passed its gates and that both builds hashed identically.
  2. Pushes dist/ostutor-sft as a NEW VERSION of the existing dataset (the files are
     replaced, earlier versions stay available on Kaggle).
  3. Writes a notebook that installs unsloth and runs the trainer under torchrun on
     both GPUs, and pushes it with --accelerator NvidiaTeslaT4 (Kaggle's "GPU T4 x2")
     and internet enabled. Pushing a kernel queues it: Kaggle runs it in the
     background, so nothing depends on this machine staying awake.
  4. --status polls; --fetch downloads the run's output (the adapter) into
     outputs/ostutor-lora-v3.

The notebook runs a 3-step smoke test first: if 16k sequences do not fit on a T4,
the run fails in minutes rather than hours.
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "dist" / "ostutor-sft"
NB_DIR = ROOT / "dist" / "kaggle_notebook"
DATASET = "divyakushpunjabi/operating-marvel-dataset"
KERNEL = "divyakushpunjabi/ostutor-v3-train"
ACCELERATOR = "NvidiaTeslaT4"          # Kaggle: "GPU T4 x2"

NOTEBOOK_CODE = '''# OSTutor v3.0 - QLoRA fine-tune of Qwen3-4B-Instruct-2507 on 2x T4 (DDP).
# Generated by tools/kaggle_launch.py. Runs unattended (Save & Run All).

# unsloth and unsloth_zoo are released as a matched pair; upgrading only one is the
# most common Kaggle breakage, so both are installed together.
!pip install -q --upgrade unsloth unsloth_zoo

import glob, json, os, subprocess, sys

# Recommended by the allocator itself in the OOM message: with variable-length rows
# (700 to 10,300 tokens) the caching allocator fragments, and an expandable segment
# reuses one growing block instead of stranding many fixed ones.
os.environ["PYTORCH_ALLOC_CONF"] = "expandable_segments:True"

# Record the environment: if this run behaves differently from an earlier one, the
# package set is the first thing to compare. Written next to the adapter.
env = {}
for mod in ("torch", "transformers", "trl", "peft", "datasets", "bitsandbytes",
            "accelerate", "unsloth", "unsloth_zoo"):
    try:
        env[mod] = __import__(mod).__version__
    except Exception as e:
        env[mod] = f"unavailable: {e}"
print(json.dumps(env, indent=1), flush=True)
!nvidia-smi --query-gpu=name,memory.total,driver_version --format=csv

script = glob.glob("/kaggle/input/**/kaggle_train.py", recursive=True)[0]
print("trainer:", script, flush=True)

def run(*extra):
    return subprocess.run([sys.executable, "-m", "torch.distributed.run",
                           "--nproc_per_node=2", script, *extra]).returncode

# 1) Smoke test: 3 steps on both GPUs, ordered LONGEST ROWS FIRST. With
#    per_device=1 and accum=8 that trains on the 48 longest rows in the dataset
#    through the real trainer, so if the worst case for memory does not fit on a T4
#    it fails here, in minutes, rather than after hours. An earlier standalone
#    "memory probe" did this outside the trainer and reported a false OOM, because
#    calling the model directly bypasses Unsloth's gradient checkpointing.
assert run("--max-steps", "3", "--longest-first",
           "--out", "/kaggle/working/smoke") == 0, \\
    "smoke test failed - stopping before the long run (no GPU quota spent on it)"
!rm -rf /kaggle/working/smoke

# 2) The real run. Checkpoints land in /kaggle/working/ostutor-lora, so if the
#    session hits Kaggle's 12 h limit the newest checkpoint is still in the output
#    and the run can resume with --resume-from.
assert run("--out", "/kaggle/working/ostutor-lora") == 0, "training failed"

out = "/kaggle/working/ostutor-lora"
with open(os.path.join(out, "environment.json"), "w") as f:
    json.dump(env, f, indent=1)
!rm -rf {out}/checkpoint-*
!ls -la {out}
'''


def run(cmd, **kw):
    print("$", " ".join(cmd), flush=True)
    return subprocess.run(cmd, text=True, capture_output=True, **kw)


def creds_ok():
    for p in (Path.home() / ".kaggle" / "kaggle.json",
              Path.home() / ".config" / "kaggle" / "kaggle.json"):
        if p.exists():
            return p
    return None


def bundle_ok():
    m = json.loads((DIST / "manifest.json").read_text(encoding="utf-8"))
    assert m["gates_passed"], "bundle did not pass its release gates"
    need = {"train.jsonl", "val.jsonl", "ood.jsonl", "manifest.json", "README.md",
            "kaggle_train.py"}
    missing = need - {p.name for p in DIST.iterdir()}
    assert not missing, f"bundle is missing {missing}"
    return m


def write_notebook():
    NB_DIR.mkdir(parents=True, exist_ok=True)
    nb = dict(cells=[dict(cell_type="code", metadata={}, source=NOTEBOOK_CODE.splitlines(True),
                          outputs=[], execution_count=None)],
              metadata=dict(kernelspec=dict(name="python3", display_name="Python 3",
                                            language="python"),
                            language_info=dict(name="python")),
              nbformat=4, nbformat_minor=4)
    (NB_DIR / "ostutor-v3-train.ipynb").write_text(json.dumps(nb, indent=1), encoding="utf-8")
    (NB_DIR / "kernel-metadata.json").write_text(json.dumps({
        "id": KERNEL,
        "title": "ostutor v3 train",
        "code_file": "ostutor-v3-train.ipynb",
        "language": "python",
        "kernel_type": "notebook",
        "is_private": True,
        "enable_gpu": True,
        "enable_tpu": False,
        "enable_internet": True,
        "dataset_sources": [DATASET],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }, indent=1), encoding="utf-8")
    return NB_DIR


def write_dataset_metadata(m):
    (DIST / "dataset-metadata.json").write_text(json.dumps({
        "title": "operating marvel dataset",
        "id": DATASET,
        "licenses": [{"name": "other"}],
    }, indent=1), encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--status", action="store_true")
    ap.add_argument("--fetch", action="store_true")
    ap.add_argument("--skip-dataset", action="store_true",
                    help="notebook only (the dataset version is already uploaded)")
    a = ap.parse_args()

    p = creds_ok()
    if not p:
        sys.exit("no Kaggle credentials: put kaggle.json in ~/.kaggle/ "
                 "(Kaggle -> Settings -> API -> Create New Token)")
    print(f"credentials: {p}")
    if subprocess.run([sys.executable, "-c", "import kaggle"], capture_output=True).returncode:
        print("installing the kaggle CLI...")
        run([sys.executable, "-m", "pip", "install", "-q", "kaggle"])

    if a.status:
        r = run([sys.executable, "-m", "kaggle", "kernels", "status", KERNEL])
        print(r.stdout or r.stderr)
        return
    if a.fetch:
        out = ROOT / "outputs" / "ostutor-lora-v3"
        out.mkdir(parents=True, exist_ok=True)
        r = run([sys.executable, "-m", "kaggle", "kernels", "output", KERNEL, "-p", str(out)])
        print(r.stdout or r.stderr)
        print("files:", sorted(x.name for x in out.rglob("*") if x.is_file())[:12])
        return

    m = bundle_ok()
    print(f"bundle {m['dataset']} {m['pipeline_version']} | train sha256 "
          f"{m['artifacts']['train.jsonl'][:16]} | gates passed")
    if a.check:
        return

    if not a.skip_dataset:
        write_dataset_metadata(m)
        r = run([sys.executable, "-m", "kaggle", "datasets", "version", "-p", str(DIST),
                 "-m", f"ostutor-sft {m['pipeline_version']} "
                       f"(train {m['artifacts']['train.jsonl'][:16]})", "--dir-mode", "zip"])
        print(r.stdout or r.stderr)
        if r.returncode:
            sys.exit("dataset upload failed")

    nb = write_notebook()
    r = run([sys.executable, "-m", "kaggle", "kernels", "push", "-p", str(nb),
             "--accelerator", ACCELERATOR])
    print(r.stdout or r.stderr)
    if r.returncode:
        sys.exit("kernel push failed")
    print(f"\nqueued on Kaggle with {ACCELERATOR} (GPU T4 x2).")
    print(f"  watch:  python tools/kaggle_launch.py --status")
    print(f"  fetch:  python tools/kaggle_launch.py --fetch")
    print(f"  web:    https://www.kaggle.com/code/{KERNEL}")


if __name__ == "__main__":
    main()
