def main():
    out = []
    for i, (q, right, wrong) in enumerate(Q):
        pos = i % 4
        choices = list(wrong)
        choices.insert(pos, right)
        assert len(choices) == 4 and len(set(choices)) == 4, q
        out.append(dict(question=q, choices=choices, answer=pos, subject="os_theory"))
    path = ROOT / "data" / "eval_theory" / "os_theory_mcq.jsonl"
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        for r in out:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"{len(out)} OS theory MCQs -> {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
